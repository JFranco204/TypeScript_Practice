export function addTwoNumbers (number1: number, number2: number): number {
    return number1 + number2;
}

//substractTwoNumbers - 
export function substractTwoNumbers (number1: number, number2: number): number{
    return number1 - number2;
}
 
//timesTwoNumbers     *
export function timesTwoNumbers (number1: number, number2: number): number {
    return number1 * number2;
}
//divideTwoNumbers    /
export function divideTwoNumbers (number1: number, number2: number): number {
    return number1 / number2;
}