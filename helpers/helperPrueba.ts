export function addTwocoins ( coin1: number, coin2: number = 0 ) {
    return coin1 + coin2;
}

export function substractTwocoins ( coin1: number, coin2: number = 0 ) {
    return coin1 - coin2;
}

export function timesTwocoins ( coin1: number, coin2: number = 0 ) {
    return coin1 * coin2;
}

export function divideTwocoins ( coin1: number, coin2: number = 0 ) {
    return coin1 / coin2;
}


export function countAge ( age1: string, age2: string ) {
    return age1 + ' ' + age2;
}