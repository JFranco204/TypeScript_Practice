export function añadeDosNumeros( num1:number, num2:number = 29 ): number {
    return num1 + num2;
}

export function restaDosNumeros( num1:number, num2:number ): number {
    return num1 - num2;
}

export function multiplicaDosNumeros( num1:number, num2:number ): number {
    return num1 * num2;
}

export function divideDosNumeros( num1:number, num2:number ): number {
    return num1 / num2;
}